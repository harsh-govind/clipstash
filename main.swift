        pin.image = NSImage(systemSymbolName: "pin.fill", accessibilityDescription: "Pinned")
        pin.contentTintColor = .systemOrange

        [icon, title, meta, pin].forEach(addSubview)
    }
    required init?(coder: NSCoder) { fatalError() }
}

final class HistoryWindow: NSObject, NSTableViewDataSource, NSTableViewDelegate,
                           NSSearchFieldDelegate, NSWindowDelegate {
    let store: Store
    let panel: KeyPanel
    let search = NSSearchField()
    let table = NSTableView()
    let emptyLabel = NSTextField(labelWithString: "Nothing here yet — copy some text or an image.")
    var items: [Clip] = []
    var onChoose: ((Clip, Bool) -> Void)?   // (clip, paste?)
    let thumbs = NSCache<NSString, NSImage>()
    let ago: RelativeDateTimeFormatter = {
        let f = RelativeDateTimeFormatter(); f.unitsStyle = .abbreviated; return f
    }()

    static let W: CGFloat = 460, H: CGFloat = 520

    init(store: Store) {
        self.store = store
        let W = Self.W, H = Self.H
        panel = KeyPanel(contentRect: NSRect(x: 0, y: 0, width: W, height: H),
                         styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: false)
        super.init()

        panel.isFloatingPanel = true
        panel.level = .popUpMenu
        panel.backgroundColor = .clear
        panel.isOpaque = false
        panel.hasShadow = true
        panel.hidesOnDeactivate = false
        panel.isReleasedWhenClosed = false
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary, .transient, .ignoresCycle]
        panel.delegate = self
        // Keep the history out of screen sharing, recordings and screenshots.
        // (Set CLIPSTASH_SHAREABLE=1 to turn this off while debugging.)
        if ProcessInfo.processInfo.environment["CLIPSTASH_SHAREABLE"] != "1" {
            panel.sharingType = .none
        }

        let bg = NSVisualEffectView(frame: NSRect(x: 0, y: 0, width: W, height: H))
        bg.material = .popover
        bg.state = .active
        bg.wantsLayer = true
        bg.layer?.cornerRadius = 14
        bg.layer?.masksToBounds = true
        bg.layer?.borderWidth = 0.5
        bg.layer?.borderColor = NSColor.separatorColor.cgColor
        panel.contentView = bg

        search.frame = NSRect(x: 12, y: H - 44, width: W - 24, height: 30)
        search.placeholderString = "Search clipboard history"
        search.font = .systemFont(ofSize: 14)
        search.focusRingType = .none
        search.delegate = self
        search.sendsSearchStringImmediately = true
        bg.addSubview(search)

        let col = NSTableColumn(identifier: .init("clip"))
        col.width = W - 16
        table.addTableColumn(col)
        table.headerView = nil
        table.rowHeight = 52
        table.intercellSpacing = NSSize(width: 0, height: 2)
        table.backgroundColor = .clear
        table.style = .plain
        table.refusesFirstResponder = true   // keep typing in the search box
        table.dataSource = self
        table.delegate = self
        table.target = self
        table.action = #selector(rowClicked)

        let scroll = NSScrollView(frame: NSRect(x: 8, y: 30, width: W - 16, height: H - 30 - 52))
        scroll.documentView = table
        scroll.hasVerticalScroller = true
        scroll.drawsBackground = false
        scroll.automaticallyAdjustsContentInsets = false
        bg.addSubview(scroll)

        emptyLabel.frame = NSRect(x: 20, y: H / 2, width: W - 40, height: 20)
        emptyLabel.alignment = .center
        emptyLabel.textColor = .secondaryLabelColor
        bg.addSubview(emptyLabel)

        let footer = NSTextField(labelWithString: "↩ paste   ⌥↩ copy only   ⌘1–9 quick paste   ⌘P pin   ⌘⌫ delete   esc close")
        footer.frame = NSRect(x: 12, y: 8, width: W - 24, height: 16)
        footer.font = .systemFont(ofSize: 10.5)
        footer.textColor = .tertiaryLabelColor
        footer.alignment = .center
        bg.addSubview(footer)

        panel.keyHandler = { [weak self] e in self?.handleKeyEquivalent(e) ?? false }
    }

    var isVisible: Bool { panel.isVisible }

    func show() {
        search.stringValue = ""
        reload()
        // Open next to the mouse pointer, kept on screen.
        let mouse = NSEvent.mouseLocation
        let scr = NSScreen.screens.first { NSMouseInRect(mouse, $0.frame, false) } ?? NSScreen.main!
        let vf = scr.visibleFrame
        let W = Self.W, H = Self.H
        var x = mouse.x - W / 2, y = mouse.y - H - 12
        if y < vf.minY { y = mouse.y + 12 }
        x = min(max(x, vf.minX + 8), vf.maxX - W - 8)
        y = min(max(y, vf.minY + 8), vf.maxY - H - 8)
        panel.setFrameOrigin(NSPoint(x: x, y: y))
        panel.makeKeyAndOrderFront(nil)
        panel.makeFirstResponder(search)
    }

    func hide() { panel.orderOut(nil) }

    func reload() {
        let q = search.stringValue.trimmingCharacters(in: .whitespaces).lowercased()
        let all = store.ordered
        items = q.isEmpty ? all : all.filter {
            $0.kind == .text ? ($0.text ?? "").lowercased().contains(q) : "image picture screenshot".contains(q)
        }
        table.reloadData()
        emptyLabel.isHidden = !items.isEmpty
        emptyLabel.stringValue = all.isEmpty ? "Nothing here yet — copy some text or an image."
                                             : "No matches"
        if !items.isEmpty { select(0) }
    }

    func select(_ row: Int) {
        guard !items.isEmpty else { return }
        let r = min(max(row, 0), items.count - 1)
        table.selectRowIndexes([r], byExtendingSelection: false)
        table.scrollRowToVisible(r)
    }

    var selected: Clip? { table.selectedRow >= 0 && table.selectedRow < items.count ? items[table.selectedRow] : nil }

    // MARK: Keys

    func control(_ control: NSControl, textView: NSTextView, doCommandBy sel: Selector) -> Bool {
        switch sel {
        case #selector(NSResponder.moveDown(_:)): select(table.selectedRow + 1); return true
        case #selector(NSResponder.moveUp(_:)): select(table.selectedRow - 1); return true
        case #selector(NSResponder.pageDown(_:)), #selector(NSResponder.scrollPageDown(_:)):
            select(table.selectedRow + 8); return true
        case #selector(NSResponder.pageUp(_:)), #selector(NSResponder.scrollPageUp(_:)):
            select(table.selectedRow - 8); return true
        case #selector(NSResponder.insertNewline(_:)), #selector(NSResponder.insertNewlineIgnoringFieldEditor(_:)):
            let copyOnly = NSApp.currentEvent?.modifierFlags.contains(.option) == true
            if let c = selected { onChoose?(c, !copyOnly) }
            return true
        case #selector(NSResponder.cancelOperation(_:)): hide(); return true
        default: return false
        }
    }

    func controlTextDidChange(_ obj: Notification) { reload() }

    func handleKeyEquivalent(_ e: NSEvent) -> Bool {
        let flags = e.modifierFlags.intersection(.deviceIndependentFlagsMask)
        guard flags.contains(.command) else { return false }
        let key = e.charactersIgnoringModifiers ?? ""
        if flags == .command, let n = Int(key), (1...9).contains(n) {
            if n <= items.count { onChoose?(items[n - 1], true) }
            return true
        }
        if flags == .command && key == "p", let c = selected {
            let row = table.selectedRow
            store.togglePin(c.id); reload(); select(row); return true
        }
        if e.keyCode == UInt16(kVK_Delete), let c = selected {   // ⌘⌫
            let row = table.selectedRow
            store.delete(c.id); reload(); select(row); return true
        }
        return false
    }

    @objc func rowClicked() {
        if table.clickedRow >= 0 && table.clickedRow < items.count { onChoose?(items[table.clickedRow], true) }
    }

    func windowDidResignKey(_ n: Notification) { hide() }

    // MARK: Table

    func numberOfRows(in tableView: NSTableView) -> Int { items.count }

    func tableView(_ tv: NSTableView, viewFor col: NSTableColumn?, row: Int) -> NSView? {
        let id = NSUserInterfaceItemIdentifier("cell")
        let cell = (tv.makeView(withIdentifier: id, owner: nil) as? ClipCell)
            ?? { let c = ClipCell(frame: NSRect(x: 0, y: 0, width: tv.bounds.width, height: 52)); c.identifier = id; return c }()
        let c = items[row]

        switch c.kind {
        case .text:
            let s = c.text ?? ""
            let flat = s.split(whereSeparator: \.isWhitespace).joined(separator: " ")
            cell.title.stringValue = String(flat.prefix(400))
            let isLink = s.hasPrefix("http://") || s.hasPrefix("https://")
            cell.icon.image = NSImage(systemSymbolName: isLink ? "link" : "text.alignleft", accessibilityDescription: nil)
            cell.icon.contentTintColor = .secondaryLabelColor
            cell.icon.imageScaling = .scaleNone
        case .image:
            let sz = c.imageSize.map { "  \(Int($0.width))×\(Int($0.height))" } ?? ""
            cell.title.stringValue = "Image" + sz
            cell.icon.image = thumbnail(c)
            cell.icon.contentTintColor = nil
            cell.icon.imageScaling = .scaleProportionallyUpOrDown
        }
        let when = ago.localizedString(for: c.date, relativeTo: Date())
        cell.meta.stringValue = row < 9 ? "⌘\(row + 1)  ·  \(when)" : when
        cell.pin.isHidden = !c.pinned
        return cell
    }

    func thumbnail(_ c: Clip) -> NSImage? {
        guard let name = c.imageFile, let url = store.imageURL(c) else { return nil }
        if let t = thumbs.object(forKey: name as NSString) { return t }
        guard let src = CGImageSourceCreateWithURL(url as CFURL, nil),
              let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceThumbnailMaxPixelSize: 96] as CFDictionary) else { return nil }
        let img = NSImage(cgImage: cg, size: .zero)
        thumbs.setObject(img, forKey: name as NSString)
        return img
    }
}

// MARK: - App

final class AppDelegate: NSObject, NSApplicationDelegate, NSMenuDelegate {
    let store = Store()
    lazy var watcher = Watcher(store: store)
    lazy var history = HistoryWindow(store: store)
    var statusItem: NSStatusItem!
    var hotKeyOK = false

    func applicationDidFinishLaunching(_ n: Notification) {
        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.variableLength)
        statusItem.autosaveName = "ClipStash"
        updateIcon()
        let menu = NSMenu()
        menu.delegate = self
        statusItem.menu = menu

        history.onChoose = { [weak self] clip, paste in self?.use(clip, paste: paste) }
        watcher.onNewClip = { [weak self] in if self?.history.isVisible == true { self?.history.reload() } }
        watcher.start()

        hotKeyAction = { [weak self] in self?.toggleHistory() }
        hotKeyOK = registerHotKey()

        // Pasting into other apps sends ⌘V, which needs Accessibility permission.
        if !AXIsProcessTrusted() {
            let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
            _ = AXIsProcessTrustedWithOptions(opts)
        }

        if ProcessInfo.processInfo.arguments.contains("--show") {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { self.history.show() }
        }
    }

    func updateIcon() {
        let name = watcher.paused ? "pause.circle" : "list.clipboard"
        let img = NSImage(systemSymbolName: name, accessibilityDescription: "ClipStash")
            ?? NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: "ClipStash")
        img?.isTemplate = true
        statusItem.button?.image = img
    }

    @objc func toggleHistory() {
        history.isVisible ? history.hide() : history.show()
    }

    func use(_ clip: Clip, paste: Bool) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch clip.kind {
        case .text:
            pb.setString(clip.text ?? "", forType: .string)
        case .image:
            guard let url = store.imageURL(clip), let data = try? Data(contentsOf: url) else { return }
            pb.declareTypes([.png, .tiff], owner: nil)
            pb.setData(data, forType: .png)
            if let tiff = NSImage(data: data)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
        }
        watcher.ignoreCurrent()
        store.touch(clip.id)
        history.hide()

        guard paste else { return }
        if AXIsProcessTrusted() {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) { Self.sendCommandV() }
        } else {
            let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
            _ = AXIsProcessTrustedWithOptions(opts)   // copied — user can press ⌘V themselves
        }
    }

    static func sendCommandV() {
        let src = CGEventSource(stateID: .hidSystemState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
        let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    // MARK: Menu bar menu (rebuilt each time it opens)

    func menuNeedsUpdate(_ menu: NSMenu) {
        menu.removeAllItems()
        let open = NSMenuItem(title: "Open Clipboard History", action: #selector(toggleHistory), keyEquivalent: "v")
        open.keyEquivalentModifierMask = [.command, .shift]
        open.target = self
        menu.addItem(open)
        if !hotKeyOK {
            let warn = NSMenuItem(title: "⚠︎ ⌘⇧V is taken by another app", action: nil, keyEquivalent: "")
            menu.addItem(warn)
        }
        menu.addItem(.separator())

        let recent = Array(store.ordered.prefix(10))
        if recent.isEmpty {
            menu.addItem(NSMenuItem(title: "No clips yet", action: nil, keyEquivalent: ""))
        }
        for (i, c) in recent.enumerated() {
            let title: String
            if c.kind == .text {
                let flat = (c.text ?? "").split(whereSeparator: \.isWhitespace).joined(separator: " ")
                title = flat.count > 50 ? String(flat.prefix(50)) + "…" : flat
            } else {
                title = "Image" + (c.imageSize.map { "  \(Int($0.width))×\(Int($0.height))" } ?? "")
            }
            let item = NSMenuItem(title: (c.pinned ? "📌 " : "") + title, action: #selector(menuPick(_:)), keyEquivalent: "")
            item.target = self
            item.tag = i
            item.representedObject = c.id.uuidString
            if c.kind == .image { item.image = history.thumbnail(c).map { resized($0, 18) } }
            menu.addItem(item)
        }

        menu.addItem(.separator())
        let pause = NSMenuItem(title: "Pause Recording", action: #selector(togglePause), keyEquivalent: "")
        pause.target = self
        pause.state = watcher.paused ? .on : .off
        menu.addItem(pause)

        let login = NSMenuItem(title: "Launch at Login", action: #selector(toggleLogin), keyEquivalent: "")
        login.target = self
        login.state = SMAppService.mainApp.status == .enabled ? .on : .off
        menu.addItem(login)

        let clear = NSMenuItem(title: "Clear History (keeps pinned)…", action: #selector(clearHistory), keyEquivalent: "")
        clear.target = self
        menu.addItem(clear)

        menu.addItem(.separator())
        let quit = NSMenuItem(title: "Quit ClipStash", action: #selector(quit), keyEquivalent: "q")
        quit.target = self
        menu.addItem(quit)
    }

    func resized(_ img: NSImage, _ side: CGFloat) -> NSImage {
        let out = NSImage(size: NSSize(width: side, height: side))
        out.lockFocus()
        img.draw(in: NSRect(x: 0, y: 0, width: side, height: side))
        out.unlockFocus()
        return out
    }

    @objc func menuPick(_ sender: NSMenuItem) {
        guard let s = sender.representedObject as? String,
              let c = store.clips.first(where: { $0.id.uuidString == s }) else { return }
        use(c, paste: false)   // from the menu: copy, then press ⌘V where you want it
    }

    @objc func togglePause() { watcher.paused.toggle(); updateIcon() }

    @objc func toggleLogin() {
        do {
            if SMAppService.mainApp.status == .enabled { try SMAppService.mainApp.unregister() }
            else { try SMAppService.mainApp.register() }
        } catch {
            NSSound.beep()
        }
    }

    @objc func clearHistory() {
        NSApp.activate(ignoringOtherApps: true)
        let a = NSAlert()
        a.messageText = "Clear clipboard history?"
        a.informativeText = "All unpinned text and images will be deleted. Pinned clips are kept."
        a.addButton(withTitle: "Clear")
        a.addButton(withTitle: "Cancel")
        a.window.sharingType = .none
        if a.runModal() == .alertFirstButtonReturn { store.clearUnpinned() }
    }

    @objc func quit() { NSApp.terminate(nil) }
}

