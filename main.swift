// ClipStash — a clipboard history for macOS.
// • Remembers text and images you copy.
// • Press ⌘⇧V anywhere to open the history, type to search, ↩ to paste.
// • The history window is excluded from screen sharing / screen capture.

import Cocoa
import Carbon
import CryptoKit
import ServiceManagement

// MARK: - Model & storage

struct Clip: Codable {
    enum Kind: String, Codable { case text, image }
    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?
    var imageSize: CGSize?
    var date = Date()
    var pinned = false
}

final class Store {
    let dir: URL, imgDir: URL, indexURL: URL
    private(set) var clips: [Clip] = []
    let maxItems = 500   // unpinned items kept; pinned ones are never trimmed

    init() {
        dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ClipStash", isDirectory: true)
        imgDir = dir.appendingPathComponent("images", isDirectory: true)
        indexURL = dir.appendingPathComponent("history.json")
        try? FileManager.default.createDirectory(at: imgDir, withIntermediateDirectories: true,
                                                 attributes: [.posixPermissions: 0o700])
        if let d = try? Data(contentsOf: indexURL),
           let c = try? JSONDecoder().decode([Clip].self, from: d) { clips = c }
    }

    /// Pinned first, then most recent.
    var ordered: [Clip] { clips.filter(\.pinned) + clips.filter { !$0.pinned } }

    func imageURL(_ c: Clip) -> URL? { c.imageFile.map { imgDir.appendingPathComponent($0) } }

    func addText(_ s: String) {
        guard !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        if let i = clips.firstIndex(where: { $0.kind == .text && $0.text == s }) {
            moveToTop(i)
        } else {
            clips.insert(Clip(kind: .text, text: s), at: 0)
        }
        trimAndSave()
    }

    func addImage(png: Data, size: CGSize) {
        let hash = SHA256.hash(data: png).prefix(16).map { String(format: "%02x", $0) }.joined()
        let name = hash + ".png"
        if let i = clips.firstIndex(where: { $0.imageFile == name }) {
            moveToTop(i)
        } else {
            let url = imgDir.appendingPathComponent(name)
            try? png.write(to: url, options: .atomic)
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            clips.insert(Clip(kind: .image, imageFile: name, imageSize: size), at: 0)
        }
        trimAndSave()
    }

    func touch(_ id: UUID) {
        if let i = clips.firstIndex(where: { $0.id == id }) { moveToTop(i); save() }
    }

    func togglePin(_ id: UUID) {
        if let i = clips.firstIndex(where: { $0.id == id }) { clips[i].pinned.toggle(); save() }
    }

    func delete(_ id: UUID) {
        if let i = clips.firstIndex(where: { $0.id == id }) { removeFile(clips.remove(at: i)); save() }
    }

    func clearUnpinned() {
        clips.filter { !$0.pinned }.forEach(removeFile)
        clips = clips.filter(\.pinned)
        save()
    }

    private func moveToTop(_ i: Int) {
        var c = clips.remove(at: i)
        c.date = Date()
        clips.insert(c, at: 0)
    }

    private func removeFile(_ c: Clip) {
        if let url = imageURL(c) { try? FileManager.default.removeItem(at: url) }
    }

    private func trimAndSave() {
        var kept: [Clip] = [], count = 0
        for c in clips {
            if c.pinned { kept.append(c) }
            else if count < maxItems { kept.append(c); count += 1 }
            else { removeFile(c) }
        }
        clips = kept
        save()
    }

    private func save() {
        guard let d = try? JSONEncoder().encode(clips) else { return }
        try? d.write(to: indexURL, options: .atomic)
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: indexURL.path)
    }
}

// MARK: - Clipboard watcher

final class Watcher {
    let store: Store
    var lastChange = NSPasteboard.general.changeCount
    var paused = false
    var onNewClip: (() -> Void)?

    /// Password managers mark secrets with these types — never record them.
    let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    init(store: Store) { self.store = store }

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.tick() }
        RunLoop.main.add(t, forMode: .common)
    }

    /// Call after ClipStash itself writes to the clipboard so it isn't re-recorded.
    func ignoreCurrent() { lastChange = NSPasteboard.general.changeCount }

    private func tick() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard !paused else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: skipTypes) else { return }

        if let s = pb.string(forType: .string) {
            store.addText(s)
        } else if let raw = pb.data(forType: .png) ?? pb.data(forType: .tiff),
                  raw.count < 40_000_000,
                  let rep = NSBitmapImageRep(data: raw),
                  let png = rep.representation(using: .png, properties: [:]) {
            store.addImage(png: png, size: CGSize(width: rep.pixelsWide, height: rep.pixelsHigh))
        } else {
            return
        }
        onNewClip?()
    }
}

// MARK: - Global hotkey (⌘⇧V) via Carbon — needs no extra permission

var hotKeyAction: (() -> Void)?

@discardableResult
func registerHotKey() -> Bool {
    var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
    InstallEventHandler(GetApplicationEventTarget(), { _, _, _ -> OSStatus in
        DispatchQueue.main.async { hotKeyAction?() }
        return noErr
    }, 1, &spec, nil, nil)
    var ref: EventHotKeyRef?
    let id = EventHotKeyID(signature: OSType(0x434C_5354), id: 1)   // 'CLST'
    let status = RegisterEventHotKey(UInt32(kVK_ANSI_V), UInt32(cmdKey | shiftKey), id,
                                     GetApplicationEventTarget(), 0, &ref)
    return status == noErr
}

// MARK: - History window

final class KeyPanel: NSPanel {
    var keyHandler: ((NSEvent) -> Bool)?
    override var canBecomeKey: Bool { true }
    override var canBecomeMain: Bool { false }
    override func performKeyEquivalent(with e: NSEvent) -> Bool {
        if keyHandler?(e) == true { return true }
        return super.performKeyEquivalent(with: e)
    }
}

